// ── Helpers ──────────────────────────────────────────────────────

function readJSON(rel) {
  const p = path.join(ROOT, rel);
  return fs.existsSync(p) ? JSON.parse(fs.readFileSync(p, "utf8")) : {};
}

function writeYAML(rel, obj) {
  const lines = [];
  function emit(obj, indent) {
    if (Array.isArray(obj)) {
      if (obj.length === 0) { lines.push("[]"); return; }
      for (const item of obj) {
        if (typeof item === "object" && item !== null) {
          const keys = Object.keys(item);
          if (keys.length === 1) {
            lines.push(" ".repeat(indent) + `- ${keys[0]}: ${JSON.stringify(item[keys[0]])}`);
          } else {
            lines.push(" ".repeat(indent) + "-");
            emitObj(item, indent + 2);
          }
        } else {
          lines.push(" ".repeat(indent) + `- ${JSON.stringify(item)}`);
        }
      }
    } else {
      emitObj(obj, indent);
    }
  }
  function emitObj(obj, indent) {
    for (const [k, v] of Object.entries(obj)) {
      if (v === null || v === undefined) continue;
      if (typeof v === "object") {
        lines.push(" ".repeat(indent) + `${k}:`);
        emit(v, indent + 2);
      } else if (typeof v === "boolean") {
        lines.push(" ".repeat(indent) + `${k}: ${v ? "true" : "false"}`);
      } else {
        lines.push(" ".repeat(indent) + `${k}: ${typeof v === "string" && v.includes(":") ? JSON.stringify(v) : v}`);
      }
    }
  }
  lines.push(`# Generated by compile-runtime.mjs at ${new Date().toISOString()}`);
  emit(obj, 0);
  fs.writeFileSync(path.join(ROOT, rel), lines.join("\n") + "\n");
}

function writeJSONFile(rel, obj) {
  fs.writeFileSync(path.join(ROOT, rel), JSON.stringify(obj, null, 2) + "\n");
}

function writeFile(rel, content) {
  fs.writeFileSync(path.join(ROOT, rel), content);
}

