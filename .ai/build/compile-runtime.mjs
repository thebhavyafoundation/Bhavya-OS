function inferPackageType(pkg) {
  const n = (pkg.name || "").toLowerCase();
  if (n.includes("ui") || n === "ui") return "component-library";
  if (n.includes("runtime")) return "runtime";
  if (n.includes("bdl") || n.includes("design")) return "design-language";
  if (n.includes("bdx") || n.includes("dev")) return "developer-tools";
  if (n.includes("docs")) return "content-registry";
  if (n.includes("brand")) return "branding";
  if (n.includes("chart")) return "charts";
  if (n.includes("icon")) return "icons";
  if (n.includes("map")) return "maps";
  if (n.includes("auth")) return "auth";
  if (n.includes("config")) return "configuration";
  if (n.includes("database") || n.includes("db")) return "database";
  if (n.includes("typescript") || n.includes("ts")) return "configuration";
  if (n.includes("eslint") || n.includes("lint")) return "configuration";
  return "library";
}

