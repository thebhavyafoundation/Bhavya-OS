/**
 * Bhavya OS v3 — Git Operations
 * Automatic Git lifecycle: create worktree → branch → implement →
 * test → self-review → commit → generate PR summary → wait for approval.
 * Never modifies master directly.
 */

import { execSync } from "child_process";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "fs";
import { join } from "path";
import { EventBus, EventTypes } from "./event-bus.mjs";

const ROOT = join(import.meta.dirname, "../..");

export class GitOperations {
  constructor(config = {}) {
    this.eventBus = config.eventBus || new EventBus();
    this.root = config.root || ROOT;
    this.worktreesDir = config.worktreesDir || join(this.root, ".worktrees");
    mkdirSync(this.worktreesDir, { recursive: true });
  }

  // ── Create Branch ──────────────────────────────────────────

  createBranch(branchName) {
    try {
      execSync(`git branch ${branchName}`, {
        cwd: this.root, encoding: "utf-8", stdio: "pipe", shell: "powershell.exe",
      });
      this.eventBus.emit("git.branch.created", { branch: branchName }, "git-ops");
      return true;
    } catch (e) {
      if (e.message.includes("already exists")) return true;
      throw e;
    }
  }

  // ── Create Worktree ────────────────────────────────────────

  createWorktree(taskId, branchName) {
    const worktreePath = join(this.worktreesDir, `wt-${taskId}`);
    const branch = branchName || `task/${taskId}`;

    this.createBranch(branch);

    try {
      execSync(`git worktree add "${worktreePath}" ${branch}`, {
        cwd: this.root, encoding: "utf-8", stdio: "pipe", shell: "powershell.exe",
      });
    } catch {
      // Worktree may already exist
      if (!existsSync(worktreePath)) throw new Error(`Failed to create worktree at ${worktreePath}`);
    }

    this.eventBus.emit("git.worktree.created", {
      taskId, branch, path: worktreePath,
    }, "git-ops");

    return { path: worktreePath, branch };
  }

  // ── Commit ─────────────────────────────────────────────────

  commit(worktreePath, message, files = []) {
    try {
      if (files.length > 0) {
        execSync(`git add ${files.join(" ")}`, {
          cwd: worktreePath, encoding: "utf-8", stdio: "pipe", shell: "powershell.exe",
        });
      } else {
        execSync("git add -A", {
          cwd: worktreePath, encoding: "utf-8", stdio: "pipe", shell: "powershell.exe",
        });
      }

      execSync(`git commit -m "${message}"`, {
        cwd: worktreePath, encoding: "utf-8", stdio: "pipe", shell: "powershell.exe",
      });

      const hash = execSync("git rev-parse --short HEAD", {
        cwd: worktreePath, encoding: "utf-8", shell: "powershell.exe",
      }).trim();

      this.eventBus.emit("git.committed", {
        path: worktreePath, hash, message,
      }, "git-ops");

      return hash;
    } catch (e) {
      if (e.message.includes("nothing to commit")) return null;
      throw e;
    }
  }

  // ── Get Diff ───────────────────────────────────────────────

  getDiff(worktreePath, base = "master") {
    try {
      return execSync(`git diff ${base} --stat`, {
        cwd: worktreePath, encoding: "utf-8", shell: "powershell.exe",
      });
    } catch { return ""; }
  }

  getFullDiff(worktreePath, base = "master") {
    try {
      return execSync(`git diff ${base}`, {
        cwd: worktreePath, encoding: "utf-8", shell: "powershell.exe",
      });
    } catch { return ""; }
  }

  // ── Generate PR Summary ────────────────────────────────────

  generatePRSummary(task, worktreePath) {
    const diff = this.getDiff(worktreePath);
    const filesChanged = diff.split("\n").filter(l => l.includes("=>") || l.includes("|")).length;
    const branch = `task/${task.id}`;

    const summary = {
      title: `[${task.type.toUpperCase()}] ${task.title}`,
      body: [
        `## ${task.title}`,
        "",
        `**Type:** ${task.type}`,
        `**Priority:** ${task.priority}`,
        `**Task ID:** ${task.id}`,
        "",
        "### Description",
        task.description,
        "",
        "### Changes",
        `- Files changed: ${filesChanged}`,
        `- Branch: \`${branch}\``,
        "",
        "### Acceptance Criteria",
        ...(task.acceptanceCriteria || []).map(c => `- [ ] ${c}`),
        "",
        "### Evidence",
        ...(task.evidence || []).map(e => `- ${e.type}: ${e.description}`),
        "",
        "---",
        "*Generated by Bhavya OS Autonomous Engineering Runtime*",
      ].join("\n"),
      head: branch,
      base: "master",
    };

    this.eventBus.emit("git.pr.generated", {
      taskId: task.id,
      title: summary.title,
      branch,
      filesChanged,
    }, "git-ops");

    return summary;
  }

  // ── Push Branch ────────────────────────────────────────────

  pushBranch(worktreePath, branch) {
    try {
      execSync(`git push origin ${branch}`, {
        cwd: worktreePath, encoding: "utf-8", stdio: "pipe", shell: "powershell.exe",
        timeout: 60000,
      });
      this.eventBus.emit("git.branch.pushed", { branch }, "git-ops");
      return true;
    } catch (e) {
      console.error(`Push failed: ${e.message}`);
      return false;
    }
  }

  // ── Merge to Master ────────────────────────────────────────

  mergeToMaster(worktreePath, branch) {
    try {
      execSync(`git checkout master && git merge ${branch} --no-ff -m "Merge ${branch}"`, {
        cwd: this.root, encoding: "utf-8", stdio: "pipe", shell: "powershell.exe",
      });
      this.eventBus.emit("git.merged", { branch, target: "master" }, "git-ops");
      return true;
    } catch (e) {
      console.error(`Merge failed: ${e.message}`);
      return false;
    }
  }

  // ── Cleanup Worktree ───────────────────────────────────────

  cleanupWorktree(taskId) {
    const worktreePath = join(this.worktreesDir, `wt-${taskId}`);
    if (!existsSync(worktreePath)) return;

    try {
      execSync(`git worktree remove "${worktreePath}" --force`, {
        cwd: this.root, encoding: "utf-8", stdio: "pipe", shell: "powershell.exe",
      });
      this.eventBus.emit("git.worktree.removed", { taskId }, "git-ops");
    } catch {}
  }

  // ── Get Status ─────────────────────────────────────────────

  getStatus() {
    try {
      const branch = execSync("git rev-parse --abbrev-ref HEAD", {
        cwd: this.root, encoding: "utf-8", shell: "powershell.exe",
      }).trim();
      const status = execSync("git status --porcelain", {
        cwd: this.root, encoding: "utf-8", shell: "powershell.exe",
      }).trim();
      const worktrees = execSync("git worktree list", {
        cwd: this.root, encoding: "utf-8", shell: "powershell.exe",
      }).trim().split("\n").filter(Boolean);

      return {
        branch,
        isDirty: status.length > 0,
        uncommittedFiles: status ? status.split("\n").length : 0,
        worktrees: worktrees.length,
      };
    } catch { return { branch: "unknown", isDirty: false, uncommittedFiles: 0, worktrees: 0 }; }
  }
}
