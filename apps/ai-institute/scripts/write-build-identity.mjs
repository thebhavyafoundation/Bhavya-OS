#!/usr/bin/env node
/**
 * Write the build identity into the bundle.
 *
 * The preview worker is shared between branches, so a deployment from one pull
 * request replaces the previous one. To know which commit is serving, the
 * commit is recorded in a module that the build inlines.
 *
 * Usage:
 *   node apps/ai-institute/scripts/write-build-identity.mjs
 *
 * Environment:
 *   GITHUB_SHA       the commit to record; the script does nothing without it
 *   BUILD_TIME       the build time; defaults to now, in UTC
 *
 * The script never fails the build: a build without an identity is a build
 * whose identity endpoint answers "unknown", which is honest. A script that
 * fails here would fail the whole build for a cosmetic problem.
 */

import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const TARGET = resolve(HERE, "../src/lib/build-info.generated.ts");

const commit = (process.env.GITHUB_SHA ?? "").trim();
const builtAt = (process.env.BUILD_TIME ?? new Date().toISOString()).trim();

if (!commit) {
  console.log(
    "build-identity: GITHUB_SHA is not set; leaving the placeholder in place.",
  );
  process.exit(0);
}

const content = `/**
 * Build identity, written into the bundle at build time.
 *
 * Generated by apps/ai-institute/scripts/write-build-identity.mjs. The
 * committed placeholder says "unknown"; a build that recorded an identity
 * carries it here.
 */
export const BUILD_INFO: { commit: string; builtAt: string } = {
  commit: ${JSON.stringify(commit)},
  builtAt: ${JSON.stringify(builtAt)},
};
`;

writeFileSync(TARGET, content, "utf-8");
console.log(`build-identity: recorded ${commit} at ${builtAt}`);
